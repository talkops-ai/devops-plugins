def portable_mcp(servers: dict[str, Any]) -> tuple[dict[str, Any], list[str]]:
    """Convert Claude-style servers to Agent Plugins 1.0.0 mcp.json entries.

    Returns (servers, notes). The portable format expands only ${PLUGIN_ROOT}/${PLUGIN_DATA}
    (in args/env/cwd), takes literal headers, and has no `timeout`; so env values with other
    ${...} expansions are dropped and remote servers that need expansion are skipped.
    """
    out: dict[str, Any] = {}
    notes: list[str] = []
    for name, conf in servers.items():
        if conf.get("url"):
            if NON_PORTABLE_RE.search(conf["url"]) or any("${" in v for v in conf.get("headers", {}).values()):
                notes.append(f"skipped {name} (needs host env expansion)")
                continue
            entry = {"type": "sse" if conf.get("type") == "sse" else "streamable-http", "url": conf["url"]}
            if conf.get("headers"):
                entry["headers"] = conf["headers"]
            out[name] = entry
            continue
        if any(NON_PORTABLE_RE.search(a) for a in conf.get("args", [])):
            notes.append(f"skipped {name} (args need host env expansion)")
            continue
        entry = {"type": "stdio", "command": conf["command"]}
        if conf.get("args"):
            entry["args"] = conf["args"]
        env = {k: v for k, v in conf.get("env", {}).items() if not NON_PORTABLE_RE.search(v)}
        if env:
            entry["env"] = env
        if conf.get("cwd"):
            entry["cwd"] = conf["cwd"]
        out[name] = entry
    return out, notes


def identity(cfg: dict, plugin: dict) -> dict[str, Any]:
    """Manifest fields shared by the Claude Code, portable, and Codex manifests.

    Defaults come from the map's `defaults`; a plugin may override IDENTITY_OVERRIDES
    (partner plugins keep the vendor's author, homepage, repository, and license).
    """
    d = cfg["defaults"]
    manifest = {
        "name": plugin["name"],
        "version": plugin.get("version", d["version"]),
        "description": plugin["description"],
    }
    manifest.update({k: plugin.get(k, d[k]) for k in IDENTITY_OVERRIDES})
    manifest["keywords"] = plugin.get("keywords", [])
    return manifest


def codex_overlay(cfg: dict, plugin: dict, has_mcp: bool, has_hooks: bool) -> dict[str, Any]:
    """.codex-plugin/plugin.json: Codex paths plus the Plugins Directory `interface` card."""
    host = cfg["hosts"]["codex"]
    manifest = identity(cfg, plugin)
    manifest["skills"] = "./skills/"
    if has_mcp:
        # The portable mcp.json, not .mcp.json: Codex does not expand ${VAR:-default}.
        manifest["mcpServers"] = "./mcp.json"
    if has_hooks:
        manifest["hooks"] = "./hooks/hooks.json"
    kind = kind_of(plugin)
    interface = {
        "displayName": plugin["displayName"],
        "shortDescription": first_sentence(re.split(r"[:;]\s|\.\s", plugin["description"])[0], 120),
        "longDescription": plugin["description"],
        "developerName": host["developerName"],
        "category": host["category"],
        "capabilities": ["Read"] if plugin.get("aws_read_only") else ["Read", "Write"],
        "websiteURL": f"{host['websiteURL']}/tree/main/{KIND_ROOTS[kind].relative_to(REPO_ROOT).as_posix()}/{plugin['name']}",
        "brandColor": host["brandColor"],
    }
    if plugin.get("defaultPrompt"):
        interface["defaultPrompt"] = plugin["defaultPrompt"][:3]
    interface.update(plugin.get("codex_interface", {}))
    manifest["interface"] = interface
    return manifest


def render_codex_agent(plugin: dict, agent_md: Path) -> str:
    """Codex custom agent (~/.codex/agents/<name>.toml) from the hand-authored Claude agent file."""
    text = agent_md.read_text()
    fm = parse_frontmatter(text)
    _, body = split_frontmatter(text)
    name = plugin["name"]
    preamble = (
        f"You are running as a Codex custom agent built from the {name} plugin. "
        "When this prompt names an MCP tool as mcp__plugin_<plugin>_<server>__<tool>, use the same tool as "
        "mcp__<server>__<tool>. Claude Code-only features this prompt mentions (the Skill tool, TodoWrite, "
        "slash commands) map to Codex skills, your plan, and plain instructions."
    )
    if plugin.get("aws_read_only"):
        preamble += (
            " You are read-only on AWS: never run commands or MCP calls that create, change, or delete AWS "
            "resources. Hand those to the user or the owning agent instead."
        )
    instructions = preamble + "\n\n" + body.strip() + "\n"
    if "'''" in instructions:
        dev = _toml_str(instructions)
    else:
        dev = "'''\n" + instructions + "'''"
    return "\n".join([
        f"# Generated by scripts/sync_aws_plugins.py from agents/{name}.md. Do not edit.",
        f"# Install: copy to ~/.codex/agents/ (or <project>/.codex/agents/) and install the {name} plugin",
        "# so its skills and MCP servers are available to this agent.",
        f"name = {_toml_str(name)}",
        f"description = {_toml_str(fm.get('description', plugin['description']))}",
        f"developer_instructions = {dev}",
        "",
    ])


