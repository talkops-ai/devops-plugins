class SyncError(RuntimeError):
    pass


def kind_of(plugin: dict) -> str:
    kind = plugin.get("kind", "agent")
    if kind not in KIND_ROOTS:
        raise SyncError(f"{plugin['name']}: unknown kind '{kind}'")
    return kind


def resolve_source(cfg: dict, ref: str) -> Path:
    """'toolkit/aws-core' -> <repo>/reference/agent-toolkit-for-aws/plugins/aws-core"""
    key, _, plugin = ref.partition("/")
    if key not in cfg["sources"]:
        raise SyncError(f"Unknown source key '{key}' in '{ref}'")
    path = REPO_ROOT / cfg["sources"][key]["path"] / plugin
    if not path.is_dir():
        raise SyncError(f"Source not found: {path} (is reference/ checked out?)")
    return path


def skills_root(cfg: dict, ref: str) -> Path:
    """Directory holding <skill>/SKILL.md dirs for a skill source ref.

    Plugin-style sources keep skills under <plugin>/skills; flat sources (the
    toolkit's skills/ tree) keep them directly under the referenced category.
    """
    root = resolve_source(cfg, ref)
    return root if cfg["sources"][ref.partition("/")[0]].get("flat") else root / "skills"


def resolve_rewrites(cfg: dict, entries: list) -> list[dict]:
    """Expand named templates from rewrites_catalog; inline dicts pass through."""
    out: list[dict] = []
    catalog = cfg.get("rewrites_catalog", {})
    for entry in entries:
        if isinstance(entry, str):
            if entry not in catalog:
                raise SyncError(f"Rewrite template '{entry}' not in rewrites_catalog")
            out.extend(copy.deepcopy(catalog[entry]))
        else:
            out.append(entry)
    return out


def make_ignore(patterns: list[str]):
    def _ignore(_dir: str, names: list[str]) -> set[str]:
        return {n for n in names if any(fnmatch.fnmatch(n, p) for p in patterns)}

    return _ignore


def copy_path(src: Path, dst: Path, ignore) -> None:
    if not src.exists():
        raise SyncError(f"Missing upstream path: {src}")
    dst.parent.mkdir(parents=True, exist_ok=True)
    if src.is_dir():
        shutil.copytree(src, dst, ignore=ignore, dirs_exist_ok=True, symlinks=False)
    else:
        shutil.copy2(src, dst)


def resolve_mcp(cfg: dict, entries: list) -> dict[str, Any]:
    catalog = cfg["mcp_catalog"]
    servers: dict[str, Any] = {}
    for entry in entries:
        if isinstance(entry, str):
            if entry not in catalog:
                raise SyncError(f"MCP server '{entry}' not in mcp_catalog")
            servers[entry] = copy.deepcopy(catalog[entry])
            continue
        for name, conf in entry.items():
            conf = copy.deepcopy(conf)
            ref = conf.pop("$ref", None)
            if ref:
                if ref not in catalog:
                    raise SyncError(f"MCP $ref '{ref}' not in mcp_catalog")
                base = copy.deepcopy(catalog[ref])
                base.update(conf)
                conf = base
            servers[name] = conf
    for name, conf in servers.items():
        if "disabled" in conf:
            # Claude Code ignores "disabled" in plugin .mcp.json and starts the server anyway.
            raise SyncError(f"MCP server '{name}' uses 'disabled'; model it as a connector instead")
    return servers


def mcp_notes(cfg: dict, entries: list) -> dict[str, str]:
    """Collect $comment notes per resolved server name for the README."""
    notes: dict[str, str] = {}
    catalog = cfg["mcp_catalog"]
    for entry in entries:
        if isinstance(entry, str):
            notes[entry] = catalog.get(entry, {}).get("$comment", "")
        else:
            for name, conf in entry.items():
                ref = conf.get("$ref")
                notes[name] = conf.get("$comment") or (catalog.get(ref, {}).get("$comment", "") if ref else "")
    return notes


def merge_hooks(cfg: dict, plugin: dict) -> tuple[dict, list[tuple[str, str]], list[dict]]:
    """Return (hooks_json_events, files_to_copy[(src_ref_path, dst)], rewrites)."""
    events: dict[str, list] = {}
    files: list[tuple[str, str]] = []
    rewrites: list[dict] = []
    for name in plugin.get("hooks", []):
        tpl = cfg["hooks_catalog"].get(name)
        if not tpl:
            raise SyncError(f"Hook template '{name}' not in hooks_catalog")
        for ev, items in tpl["hooks"].items():
            events.setdefault(ev, []).extend(copy.deepcopy(items))
        files.extend(tpl.get("files", {}).items())
        rewrites.extend(resolve_rewrites(cfg, tpl.get("rewrites", [])))
    for ev, items in plugin.get("hooks_inline", {}).items():
        events.setdefault(ev, []).extend(copy.deepcopy(items))
    return events, files, rewrites


def apply_rewrites(target: Path, rewrites: list[dict]) -> None:
    for rw in rewrites:
        path = target / rw["path"]
        if not path.is_file():
            raise SyncError(f"Rewrite target missing: {path}")
        text = path.read_text()
        if rw["find"] not in text:
            if rw["replace"] in text:
                continue  # already applied
            raise SyncError(f"Rewrite anchor not found in {path} (upstream drift?): {rw['find']!r}")
        path.write_text(text.replace(rw["find"], rw["replace"]))


def resolve_connectors(cfg: dict, plugin: dict) -> dict[str, dict]:
    catalog = cfg.get("connector_catalog", {})
    out: dict[str, dict] = {}
    for key in plugin.get("connectors", []):
        if key not in catalog:
            raise SyncError(f"{plugin['name']}: connector '{key}' not in connector_catalog")
        out[key] = catalog[key]
    return out


def describe_server(conf: dict) -> tuple[str, str]:
    if conf.get("url"):
        return "http", f"`{conf['url']}`"
    args = conf.get("args", [])
    if conf.get("command") == "docker":
        image = next((a for a in reversed(args) if not a.startswith("-")), "")
        return "stdio", f"`docker run {image}`"
    pkg = next((a for a in args if not a.startswith("-") and a != "--from"), "")
    if "--from" in args:
        pkg = args[args.index("--from") + 1]
    flags = " ".join(a for a in args if a.startswith("--") and a != "--from")
    return "stdio", f"`{conf.get('command', '')} {pkg}`" + (f" `{flags}`" if flags else "")


def _shell_join(parts: list[str]) -> str:
    return " ".join(shlex.quote(p) for p in parts)


def _toml_str(value: str) -> str:
    """TOML basic string. JSON string escapes (\\" \\\\ \\n \\uXXXX) are valid TOML."""
    return json.dumps(value, ensure_ascii=False)


def _toml_array(values: list[str]) -> str:
    return "[" + ", ".join(_toml_str(v) for v in values) + "]"


def connector_snippets(key: str, c: dict) -> tuple[str, str, str]:
    """(Claude Code CLI, Codex CLI, Codex config.toml) snippets for one connector."""
    env = c.get("env", {})
    launch = _shell_join([c["command"], *c.get("args", [])])
    env_flags = " ".join(f"--env {shlex.quote(f'{k}={v}')}" for k, v in env.items())
    claude = f"claude mcp add --scope user {env_flags + ' ' if env_flags else ''}{key} -- {launch}"
    codex = f"codex mcp add {key} {env_flags + ' ' if env_flags else ''}-- {launch}"
    toml = [f"[mcp_servers.{key}]", f"command = {_toml_str(c['command'])}", f"args = {_toml_array(c.get('args', []))}"]
    if env:
        toml.append("env = { " + ", ".join(f"{k} = {_toml_str(v)}" for k, v in env.items()) + " }")
    return claude, codex, "\n".join(toml)


