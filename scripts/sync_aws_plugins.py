#!/usr/bin/env python3
"""Sync upstream AWS skills (under reference/) into TalkOps agent and vertical plugins.

Reads scripts/aws-plugin-map.json and, for each mapped plugin:

  * copies the mapped skills (and extra dirs: commands, scripts, fixtures, ...)
  * writes the Claude Code layout: .claude-plugin/plugin.json, .mcp.json, hooks/hooks.json
  * writes the portable Agent Plugins 1.0.0 layout: plugin.json, mcp.json (Codex, Cursor, ...)
  * writes the Codex overlay .codex-plugin/plugin.json and, for agent plugins, a Codex
    custom-agent file codex/agents/<name>.toml rendered from agents/<name>.md
  * applies declared text rewrites (fails loudly if upstream drifted)
  * writes CONNECTORS.md for opt-in, connection-bound MCP servers (Claude Code and Codex snippets)
  * regenerates the plugin README.md
  * upserts the plugin entry in .claude-plugin/marketplace.json and regenerates the Codex
    marketplace .agents/plugins/marketplace.json
  * on a full sync, renders docs/mcp-server-coverage.md from mcp_upstream_index

Plugin kinds ("kind" in the map):

  * agent    -> plugins/agent-plugins/<name>/    (agents/<name>.md is hand-authored)
  * vertical -> plugins/vertical-plugins/<name>/ (commands/ is hand-authored)
  * partner  -> plugins/partner-built/<name>/    (vendor content, vendor identity; attaches to the main agent)

Hand-authored files are never touched. Re-run after pulling upstream changes:

    python3 scripts/sync_aws_plugins.py            # all plugins
    python3 scripts/sync_aws_plugins.py --only aws-sre-agent aws-networking
    python3 scripts/sync_aws_plugins.py --kind vertical
    python3 scripts/sync_aws_plugins.py --dry-run  # report only
"""

